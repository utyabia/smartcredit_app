import streamlit as st
import pandas as pd
import numpy as np
import joblib
import os

# Page Configuration
st.set_page_config(
    page_title="SmartCredit - Credit Risk Assessor",
    page_icon="💳",
    layout="wide"
)

# Mock model to use if the pickle file is missing
class FallbackModel:
    def predict_proba(self, df):
        score = df['credit_score'].values[0]
        dti = df['debt_to_income'].values[0]
        income = df['annual_income'].values[0]
        loan = df['loan_amount'].values[0]

        fico_factor = (850 - score) / 550  # 0 (best) to 1 (worst)
        dti_factor = min(dti / 0.8, 1.0)   # 0 to 1
        income_factor = min(loan / max(income, 1), 1.0) # 0 to 1

        prob = (fico_factor * 0.5) + (dti_factor * 0.3) + (income_factor * 0.2)
        prob = max(0.01, min(0.99, prob))
        return np.array([[1 - prob, prob]])

# Load Saved Model Artifact
@st.cache_resource
def load_credit_model():
    model_path = 'credit_default_model.pkl'
    if os.path.exists(model_path):
        return joblib.load(model_path)
    else:
        st.warning("⚠️ 'credit_default_model.pkl' not found. Using a fallback rule-based model for demonstration.")
        return FallbackModel()

model = load_credit_model()

# Application Header
st.title("💳 SmartCredit: AI Credit Risk Assessment System")
st.markdown("""
This web application predicts loan default probability and classifies credit risk for applicants
using a machine learning model.
""")

st.divider()

# Sidebar - User Input Form
st.sidebar.header("📋 Applicant Profile Data")

income = st.sidebar.number_input(
    "Annual Income ($)",
    min_value=10000,
    max_value=300000,
    value=65000,
    step=2500
)

loan_req = st.sidebar.number_input(
    "Requested Loan Amount ($)",
    min_value=1000,
    max_value=100000,
    value=15000,
    step=1000
)

score = st.sidebar.slider(
    "Credit Score (FICO)",
    min_value=300,
    max_value=850,
    value=680
)

dti = st.sidebar.slider(
    "Debt-to-Income Ratio (DTI)",
    min_value=0.0,
    max_value=0.80,
    value=0.25,
    step=0.01
)

emp_yrs = st.sidebar.slider(
    "Employment Duration (Years)",
    min_value=0,
    max_value=35,
    value=5
)

# Main Screen Evaluation Logic
col1, col2 = st.columns([1, 1])

with col1:
    st.subheader("Summary of Input Data")
    applicant_df = pd.DataFrame([{
        'annual_income': income,
        'loan_amount': loan_req,
        'credit_score': score,
        'debt_to_income': dti,
        'employment_years': emp_yrs
    }])

    st.dataframe(applicant_df.T.rename(columns={0: "Submitted Value"}), use_container_width=True)

with col2:
    st.subheader("Underwriting Decision")

    if st.button("Evaluate Credit Risk", type="primary"):
        # Model Inference
        default_prob = model.predict_proba(applicant_df)[0][1] # Probability of Default (Class 1)

        st.metric(label="Default Probability Score", value=f"{default_prob * 100:.1f}%")

        # Risk Classification Logic
        if default_prob < 0.30:
            st.success("Risk Level: LOW RISK")
            st.write("**Underwriting Recommendation:** Approve loan request standard interest rate.")
        elif default_prob < 0.55:
            st.warning("Risk Level: MEDIUM RISK")
            st.write("**Underwriting Recommendation:** Approve with additional collateral or elevated interest rate.")
        else:
            st.error("Risk Level: HIGH RISK")
            st.write("**Underwriting Recommendation:** Decline application due to excessive risk of default.")